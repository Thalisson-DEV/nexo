WITH normalizados AS (
    SELECT
        btrim(nome_fantasia) AS nome_fantasia,
        documento_informado,
        CASE
            WHEN regexp_replace(COALESCE(documento_informado, ''), '[^0-9]', '', 'g') ~ '^[0-9]{14}$'
                 AND regexp_replace(documento_informado, '[^0-9]', '', 'g') NOT LIKE '00000000%'
                THEN regexp_replace(documento_informado, '[^0-9]', '', 'g')
            ELSE NULL
        END AS documento
    FROM tmp_fornecedores_frota
), documentados AS (
    SELECT
        MIN(nome_fantasia) AS nome_fantasia,
        documento,
        CASE
            WHEN COUNT(DISTINCT nome_fantasia) > 1 THEN
                'Outros nomes informados na importação: '
                || string_agg(DISTINCT nome_fantasia, ' | ' ORDER BY nome_fantasia)
            ELSE NULL
        END AS observacoes
    FROM normalizados
    WHERE documento IS NOT NULL
    GROUP BY documento
), sem_documento AS (
    SELECT DISTINCT ON (immutable_unaccent(lower(nome_fantasia)))
        nome_fantasia,
        NULL::VARCHAR(14) AS documento,
        CASE
            WHEN documento_informado IS NOT NULL THEN
                'Documento informado na importação, pendente de correção: ' || documento_informado
            ELSE 'CNPJ não informado na importação.'
        END AS observacoes
    FROM normalizados
    WHERE documento IS NULL
      AND NOT EXISTS (
          SELECT 1
          FROM normalizados documentado
          WHERE documentado.documento IS NOT NULL
            AND immutable_unaccent(lower(documentado.nome_fantasia)) =
                immutable_unaccent(lower(normalizados.nome_fantasia))
      )
    ORDER BY immutable_unaccent(lower(nome_fantasia)), nome_fantasia
), candidatos AS (
    SELECT * FROM documentados
    UNION ALL
    SELECT * FROM sem_documento
)
